import io
import pandas as pd
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

class ReportGeneratorService:
    @staticmethod
    def generate_pdf(df, title="CyberShield AI Security Incident Analytical Report", filters_applied=None):
        """Generates a professional cybersecurity incident audit report using ReportLab"""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()

        # Custom cybersecurity styles
        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0B1020")
        )
        subtitle_style = ParagraphStyle(
            "ReportSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#64748B")
        )
        h2_style = ParagraphStyle(
            "ReportH2",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#1E293B"),
            spaceBefore=12,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor("#334155")
        )
        table_header_style = ParagraphStyle(
            "TableHeader",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=11,
            textColor=colors.white
        )
        table_cell_style = ParagraphStyle(
            "TableCell",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#1E293B")
        )
        kpi_num_style = ParagraphStyle(
            "KpiNum",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=18,
            alignment=1,
            textColor=colors.HexColor("#0284C7")
        )
        kpi_lbl_style = ParagraphStyle(
            "KpiLbl",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=10,
            alignment=1,
            textColor=colors.HexColor("#64748B")
        )

        elements = []

        # Header Title Banner
        elements.append(Paragraph(title, title_style))
        gen_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
        elements.append(Paragraph(f"Generated by CyberShield AI Threat Intelligence Platform | Report Date: {gen_time}", subtitle_style))
        elements.append(Spacer(1, 8))
        elements.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#0284C7"), spaceAfter=14))

        # Dataset Overview
        total_records = len(df)
        if total_records == 0:
            elements.append(Paragraph("<b>Notice:</b> No incident records match the specified query filters. The dataset is empty.", body_style))
            doc.build(elements)
            buffer.seek(0)
            return buffer.getvalue()

        crit_count = len(df[df["severity"] == "Critical"])
        high_count = len(df[df["severity"] == "High"])
        open_count = len(df[df["status"] == "Open"])
        resolved_count = len(df[df["status"].isin(["Resolved", "Closed"])])
        res_rate = round(resolved_count / total_records * 100, 1) if total_records > 0 else 0
        avg_res = round(df["resolution_time"].dropna().mean(), 1) if not df["resolution_time"].dropna().empty else "N/A"

        # KPI Summary Grid Table
        kpi_data = [
            [
                Paragraph(str(total_records), kpi_num_style),
                Paragraph(str(crit_count), kpi_num_style),
                Paragraph(str(high_count), kpi_num_style),
                Paragraph(str(open_count), kpi_num_style),
                Paragraph(f"{res_rate}%", kpi_num_style),
                Paragraph(f"{avg_res}h", kpi_num_style)
            ],
            [
                Paragraph("TOTAL INCIDENTS", kpi_lbl_style),
                Paragraph("CRITICAL SEVERITY", kpi_lbl_style),
                Paragraph("HIGH SEVERITY", kpi_lbl_style),
                Paragraph("OPEN & ACTIVE", kpi_lbl_style),
                Paragraph("RESOLUTION RATE", kpi_lbl_style),
                Paragraph("AVG RESOLUTION", kpi_lbl_style)
            ]
        ]
        kpi_table = Table(kpi_data, colWidths=[90, 90, 90, 90, 90, 90])
        kpi_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(kpi_table)
        elements.append(Spacer(1, 14))

        # Executive Summary & Threat Posture
        elements.append(Paragraph("1. Executive Summary & Incident Posture", h2_style))
        posture_text = (
            f"This analytical assessment covers <b>{total_records} logged cybersecurity incidents</b> across production and corporate environments. "
            f"Of these, <b>{crit_count} are classified as Critical</b> and <b>{high_count} as High Severity</b>. "
            f"The current incident resolution rate is <b>{res_rate}%</b>, with an average resolution duration of <b>{avg_res} hours</b>. "
            f"There are currently <b>{open_count} unresolved incidents</b> requiring triage attention."
        )
        elements.append(Paragraph(posture_text, body_style))
        elements.append(Spacer(1, 12))

        # Threat Category Breakdown Table
        elements.append(Paragraph("2. Threat Category Breakdown", h2_style))
        cat_counts = df["incident_type"].value_counts()
        table_rows = [[
            Paragraph("Category", table_header_style),
            Paragraph("Incidents", table_header_style),
            Paragraph("% Share", table_header_style),
            Paragraph("Top Severity", table_header_style),
            Paragraph("Resolved", table_header_style)
        ]]

        for cat, count in cat_counts.items():
            sub = df[df["incident_type"] == cat]
            pct = round((count / total_records) * 100, 1)
            top_sev = sub["severity"].mode().iloc[0] if not sub["severity"].empty else "N/A"
            res = len(sub[sub["status"].isin(["Resolved", "Closed"])])
            table_rows.append([
                Paragraph(str(cat), table_cell_style),
                Paragraph(str(count), table_cell_style),
                Paragraph(f"{pct}%", table_cell_style),
                Paragraph(str(top_sev), table_cell_style),
                Paragraph(f"{res}/{count}", table_cell_style)
            ])

        cat_table = Table(table_rows, colWidths=[160, 80, 80, 110, 110])
        cat_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0B1020")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(cat_table)
        elements.append(Spacer(1, 14))

        # Top Priority Incidents Table
        elements.append(Paragraph("3. Priority Incidents for Investigation", h2_style))
        elements.append(Paragraph("The following records represent elevated risk events based on severity rating, active triage state, and affected asset impact:", body_style))
        elements.append(Spacer(1, 6))

        priority_rows = [[
            Paragraph("ID", table_header_style),
            Paragraph("Date", table_header_style),
            Paragraph("Category", table_header_style),
            Paragraph("Severity", table_header_style),
            Paragraph("Affected System", table_header_style),
            Paragraph("Status", table_header_style)
        ]]

        # Sort: Critical first, then High, Open first
        sorted_sub = df.sort_values(by=["severity", "status"], ascending=[True, True]).head(10)
        for _, row in sorted_sub.iterrows():
            priority_rows.append([
                Paragraph(str(row.get("incident_id", "")), table_cell_style),
                Paragraph(str(row.get("incident_date", ""))[:16], table_cell_style),
                Paragraph(str(row.get("incident_type", "")), table_cell_style),
                Paragraph(str(row.get("severity", "")), table_cell_style),
                Paragraph(str(row.get("affected_system", "")), table_cell_style),
                Paragraph(str(row.get("status", "")), table_cell_style)
            ])

        prio_table = Table(priority_rows, colWidths=[70, 95, 105, 70, 120, 80])
        prio_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1E293B")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(prio_table)
        elements.append(Spacer(1, 14))

        # Recommendations & Limitations
        elements.append(Paragraph("4. Recommended Security Actions", h2_style))
        recs = [
            "<b>Containment Acceleration:</b> Assign immediate Tier-3 response handlers to unresolved Ransomware, Malware, and Data Breach incidents.",
            "<b>Defensive Posture Tuning:</b> Update Perimeter Firewall and IDS/IPS signature rules based on recurrent reconnaissance and volumetric anomalies.",
            "<b>Identity Governance:</b> Conduct an urgent credential audit for administrative service accounts exhibiting off-hours or atypical geo-locations."
        ]
        for r in recs:
            elements.append(Paragraph(f"• {r}", body_style))
            elements.append(Spacer(1, 3))

        elements.append(Spacer(1, 10))
        elements.append(Paragraph("5. Scope and Analytical Limitations", h2_style))
        limitation_text = (
            "<i>Notice: This report is generated by CyberShield AI for analytical demonstration and historical event review. "
            "Prioritization scores and classifications reflect recorded data attributes rather than live runtime packet inspection. "
            "Data generated as demonstration telemetry is flagged accordingly.</i>"
        )
        elements.append(Paragraph(limitation_text, body_style))

        # Build PDF
        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
